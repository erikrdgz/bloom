import { writeFileSync } from 'node:fs'
import { format, resolveConfig } from 'prettier'
import { fas } from '@fortawesome/free-solid-svg-icons'
import { far } from '@fortawesome/free-regular-svg-icons'
import { fab } from '@fortawesome/free-brands-svg-icons'

// Keep SVG paths out of the initial bundle. Regenerate after upgrading the packs.
const rows = []
for (const [family, pack] of [
  ['solid', fas],
  ['regular', far],
  ['brands', fab],
]) {
  const unique = new Map(Object.values(pack).map((icon) => [icon.iconName, icon]))
  for (const icon of [...unique.values()].sort((a, b) => a.iconName.localeCompare(b.iconName))) {
    const id = family === 'solid' ? icon.iconName : `${icon.prefix}-${icon.iconName}`
    rows.push([
      id,
      family,
      icon.iconName,
      icon.icon[2].filter((alias) => typeof alias === 'string'),
    ])
  }
}
const target = new URL('../src/lib/iconCatalog.ts', import.meta.url)
const source = `// Generated by scripts/generate-icon-catalog.mjs. Do not edit by hand.\nexport type IconFamily = 'solid' | 'regular' | 'brands'\nexport const iconRows: [id: string, family: IconFamily, name: string, aliases: string[]][] = [\n${rows.map((row) => `  ${JSON.stringify(row)},`).join('\n')}\n]\n`
writeFileSync(
  target,
  await format(source, { ...(await resolveConfig(target.pathname)), parser: 'typescript' }),
)
console.log(
  `${rows.length} unique icons: ${['solid', 'regular', 'brands'].map((family) => `${rows.filter((row) => row[1] === family).length} ${family}`).join(', ')}`,
)
